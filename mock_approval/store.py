_MEDIA_TYPES = {
    "pdf": "application/pdf",
    "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "png": "image/png",
    "jpg": "image/jpeg",
    "jpeg": "image/jpeg",
}


def media_type_for(file_type: str) -> str:
    return _MEDIA_TYPES.get(file_type.lower(), "application/octet-stream")


def _placeholder_bytes(file_type: str) -> bytes:
    """占位内容：M1 只验证下载/哈希/落库，不要求可解析。"""
    if file_type == "pdf":
        return b"%PDF-1.4\n% mock placeholder generated by M1\n%%EOF\n"
    if file_type == "docx":
        return b"PK\x03\x04mock-docx-placeholder-M1"
    if file_type in {"png", "jpg", "jpeg"}:
        return _PNG_1PX
    return b"mock placeholder"


def _now_iso() -> str:
    return datetime.now(_TZ).isoformat(timespec="seconds")


@dataclass
class Attachment:
    attachment_id: str
    file_name: str
    file_type: str
    missing: bool = False
    file_size: int = 0
    file_hash: str = ""

    def to_dict(self) -> dict:
        return {
            "attachment_id": self.attachment_id,
            "file_name": self.file_name,
            "file_type": self.file_type,
            "file_size": self.file_size,
            "file_hash": self.file_hash,
        }


@dataclass
class Approval:
    approval_code: str
    title: str
    applicant_name: str
    apply_date: str
    status: str
    form_data: dict[str, str]
    attachments: list[Attachment] = field(default_factory=list)

    @property
    def attachment_count(self) -> int:
        return len(self.attachments)

    def summary(self) -> dict:
        return {
            "approval_code": self.approval_code,
            "title": self.title,
            "applicant_name": self.applicant_name,
            "apply_date": self.apply_date,
            "attachment_count": self.attachment_count,
        }

    def detail(self) -> dict:
        return {
            "approval_info": {
                "approval_code": self.approval_code,
                "title": self.title,
                "applicant_name": self.applicant_name,
                "apply_date": self.apply_date,
                "status": self.status,
            },
            "form_data": dict(self.form_data),
            "attachments": [att.to_dict() for att in self.attachments],
            "current_status": self.status,
        }


class MockStore:
    """进程内状态。线程安全：写操作持锁，读操作只读快照。"""

    def __init__(self) -> None:
        self._lock = Lock()
        self.approvals: dict[str, Approval] = {}
        self.comments: dict[str, list[dict]] = {}
        self.idempotency: dict[str, dict] = {}
        self._comment_seq = 0
        self.reset()

    # ---- 生命周期 ----
    def reset(self) -> None:
        with self._lock:
            self.approvals = self._load_seed()
            self._ensure_files()
            self._refresh_file_meta()
            self.comments = {}
            self.idempotency = {}
            self._comment_seq = 0

    def _load_seed(self) -> dict[str, Approval]:
        raw = json.loads(DATA_FILE.read_text(encoding="utf-8"))
        approvals: dict[str, Approval] = {}
        for item in raw["approvals"]:
            attachments = [
                Attachment(
                    attachment_id=att["attachment_id"],
                    file_name=att["file_name"],
                    file_type=att["file_type"],
                    missing=bool(att.get("missing", False)),
                )
                for att in item.get("attachments", [])
            ]
            approval = Approval(
                approval_code=item["approval_code"],
                title=item["title"],
                applicant_name=item["applicant_name"],
                apply_date=item["apply_date"],
                status=item.get("status", "pending"),
                form_data=dict(item.get("form_data", {})),
                attachments=attachments,
            )
            approvals[approval.approval_code] = approval
        return approvals

    def _ensure_files(self) -> None:
        FILES_DIR.mkdir(parents=True, exist_ok=True)
        for approval in self.approvals.values():
            for att in approval.attachments:
                if att.missing:
                    continue
                path = FILES_DIR / att.file_name
                if not path.exists():
                    path.write_bytes(_placeholder_bytes(att.file_type))

    def _refresh_file_meta(self) -> None:
        for approval in self.approvals.values():
            for att in approval.attachments:
                if att.missing:
                    att.file_size, att.file_hash = 0, ""
                    continue
                path = FILES_DIR / att.file_name
                if not path.exists():
                    att.missing = True
                    att.file_size, att.file_hash = 0, ""
                    continue
                content = path.read_bytes()
                att.file_size = len(content)
                att.file_hash = hashlib.sha256(content).hexdigest()

    # ---- 查询 ----
    def pending(self, limit: int) -> list[Approval]:
        items = [a for a in self.approvals.values() if a.status == "pending"]
        return items[: max(0, limit)]

    def get(self, approval_code: str) -> Approval | None:
        return self.approvals.get(approval_code)

    def find_attachment(self, approval_code: str, attachment_id: str) -> Attachment | None:
        approval = self.approvals.get(approval_code)
        if not approval:
            return None
        for att in approval.attachments:
            if att.attachment_id == attachment_id:
                return att
        return None

    def attachment_path(self, approval_code: str, attachment_id: str) -> Path | None:
        att = self.find_attachment(approval_code, attachment_id)
        if not att or att.missing:
            return None
        path = FILES_DIR / att.file_name
        return path if path.exists() else None

    # ---- 评论 ----
    def add_comment(self, approval_code: str, content: str, idempotency_key: str) -> dict:
        with self._lock:
            if idempotency_key and idempotency_key in self.idempotency:
                replay = dict(self.idempotency[idempotency_key])
                replay["idempotent_replay"] = True
                return replay
            self._comment_seq += 1
            record = {
                "comment_id": f"CMT-{self._comment_seq:04d}",
                "approval_code": approval_code,
                "content": content,
                "status": "success",
                "created_at": _now_iso(),
            }
            self.comments.setdefault(approval_code, []).append(record)
            result = {
                "comment_id": record["comment_id"],
                "status": "success",
                "created_at": record["created_at"],
                "idempotent_replay": False,
            }
            if idempotency_key:
                self.idempotency[idempotency_key] = dict(result)
            return result

    def list_comments(self, approval_code: str) -> list[dict]:
        return list(self.comments.get(approval_code, []))


STORE = MockStore()
